const Context = createContext<TuiI18n>({
  locale: (): TuiLocale => "en",
  t: (source) => source,
})

export type TuiI18n = {
  locale: Accessor<TuiLocale>
  t: (source: string, params?: Record<string, string | number | boolean>) => string
}

function format(source: string, params?: Record<string, string | number | boolean>) {
  if (!params) return source
  return source.replace(/{{\s*([^}]+?)\s*}}/g, (_, key: string) => String(params[key] ?? ""))
}

export function translate(locale: TuiLocale, source: string, params?: Record<string, string | number | boolean>) {
  if (locale === "en") return format(source, params)
  return format(ja[source] ?? source, params)
}

export function TuiI18nProvider(props: ParentProps) {
  const config = useConfig()
  const locale = (): TuiLocale => (config.data.language === "en" ? "en" : "ja")
  const value = {
    locale,
    t: (source: string, params?: Record<string, string | number | boolean>) => translate(locale(), source, params),
  }
  return <Context.Provider value={value}>{props.children}</Context.Provider>
}

export function useI18n() {
  return useContext(Context)!
}
